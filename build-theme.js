#!/usr/bin/env node
'use strict';
// Builds the single CSS file for the sub-account Theme Editor ("CSS file" slot):
//   theme/existing.css     what was already uploaded (Prism theme + .gdt rules), unchanged
//   theme/canvas-theme.css  the ti_ template rules
// Output: theme-upload/canvas-upload.css. The mobile slot takes theme/canvas-mobile.css as-is.

const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, 'theme');
const outDir = path.join(__dirname, 'theme-upload');
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8').replace(/\s*$/, '\n');

const banner = (title) => `\n\n/* ${'='.repeat(70)}\n   ${title}\n   ${'='.repeat(70)} */\n\n`;

const css =
  `/* Sub-account theme CSS — generated by build-theme.js on ${new Date().toISOString().slice(0, 10)}.\n` +
  `   Edit theme/existing.css or theme/canvas-theme.css in the repo, not this file. */\n` +
  banner('EXISTING RULES (Prism code theme + .gdt) — unchanged') + read('existing.css') +
  banner('ti_ TEMPLATE (canvas-course-sync) — only affects elements with ti_ classes') + read('canvas-theme.css');

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'canvas-upload.css'), css);
fs.copyFileSync(path.join(dir, 'canvas-mobile.css'), path.join(outDir, 'canvas-mobile.css'));
console.log('Wrote theme-upload/canvas-upload.css (CSS file) and theme-upload/canvas-mobile.css (Mobile app CSS file)');
